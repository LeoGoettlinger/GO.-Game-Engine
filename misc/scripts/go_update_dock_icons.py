HEADER = ROOT / "modules/go_suite/go_suite_icons.gen.h"
ICONS = [
    ("go_git_dock.svg", "GO_SUITE_GIT_DOCK_SVG"),
    ("go_agentics_dock.svg", "GO_SUITE_AGENTICS_DOCK_SVG"),
    ("go_suite_launcher.svg", "GO_SUITE_LAUNCHER_SVG"),
]

