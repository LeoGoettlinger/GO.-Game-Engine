def cpp_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "").replace("\t", "\\t").replace("\n", "\\n")


def godot_header_lines() -> list[str]:
    name = HEADER.name
    placeholder = "$filename"
    if len(name) > len(placeholder):
        padded = placeholder + " " * (len(name) - len(placeholder))
        text = GODOT_HEADER.replace(padded, name)
    else:
        padded_name = name + " " * (len(placeholder) - len(name))
        text = GODOT_HEADER.replace(placeholder, padded_name)
    return text.splitlines()


def generated_content() -> str:
    lines = godot_header_lines()
    lines += [
        "",
        "#pragma once",
        "",
        "// GO. Game Engine — Copyright (c) 2026 SampleCraft / GO. contributors",
        "// SPDX-License-Identifier: MIT",
        "// THIS FILE IS GENERATED by misc/scripts/go_update_dock_icons.py. DO NOT EDIT.",
        "",
    ]
    for filename, constant in ICONS:
        text = (ICON_DIR / filename).read_text(encoding="utf-8").strip() + "\n"
        lines.append(f"inline constexpr const char *{constant} =")
        lines.append(f'\t\t"{cpp_escape(text)}";')
        lines.append("")
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--stdout", action="store_true")
    args = parser.parse_args()
    content = generated_content()
    if args.stdout:
        sys.stdout.write(content)
        return 0
    if args.check:
        if not HEADER.is_file() or HEADER.read_text(encoding="utf-8") != content:
            print("GO. dock icon header is out of date; run go_update_dock_icons.py", file=sys.stderr)
            return 1
        print("OK: GO. dock icon header matches the SVG sources")
        return 0
    HEADER.write_text(content, encoding="utf-8")
    print(HEADER.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
