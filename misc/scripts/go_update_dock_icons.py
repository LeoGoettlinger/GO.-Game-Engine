from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ICON_DIR = ROOT / "modules/go_suite/icons"
HEADER = ROOT / "modules/go_suite/go_suite_icons.gen.h"
ICONS = [
	("go_git_dock.svg", "GO_SUITE_GIT_DOCK_SVG"),
	("go_agentics_dock.svg", "GO_SUITE_AGENTICS_DOCK_SVG"),
	("go_suite_launcher.svg", "GO_SUITE_LAUNCHER_SVG"),
]


def cpp_escape(text: str) -> str:
	return (text.replace("\\", "\\\\")
			.replace('"', '\\"')
			.replace("\r", "")
			.replace("\t", "\\t")
			.replace("\n", "\\n"))


def generated_content() -> str:
	lines = [
		"// GO. Game Engine — Copyright (c) 2026 SampleCraft / GO. contributors",
		"// SPDX-License-Identifier: MIT",
		"// THIS FILE IS GENERATED by misc/scripts/go_update_dock_icons.py. DO NOT EDIT.",
		"#pragma once",
		"",
	]
	for filename, constant in ICONS:
		text = (ICON_DIR / filename).read_text(encoding="utf-8").strip() + "\n"
		lines.append(f'inline constexpr const char *{constant} =')
		lines.append(f'        "{cpp_escape(text)}";')
		lines.append("")
	while lines and lines[-1] == "":
		lines.pop()
	return "\n".join(lines) + "\n"


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--check", action="store_true")
	parser.add_argument("--stdout", action="store_true")
	args = parser.parse_args()
	content = generated_content()
	if args.stdout:
		sys.stdout.write(content)
		return 0
	if args.check:
		if not HEADER.is_file() or HEADER.read_text(encoding="utf-8") != content:
			print("GO. dock icon header is out of date; run go_update_dock_icons.py", file=sys.stderr)
			return 1
		print("OK: GO. dock icon header matches the SVG sources")
		return 0
	HEADER.write_text(content, encoding="utf-8")
	print(HEADER.relative_to(ROOT))
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
